// Extensible Language Registry: allows adding gu, ta, te, bn, pa, kn, ml smoothly
function registerLocale(langCode, translations) {
  if (langCode && typeof translations === 'object') {
    LOCALES[langCode] = Object.assign({}, LOCALES.en, translations);
  }
}

// Helper to get active locale dictionary safely
function getLocaleDict(langCode) {
  return LOCALES[langCode] || LOCALES.en;
}

window.LOCALES = LOCALES;
window.registerLocale = registerLocale;
window.getLocaleDict = getLocaleDict;
